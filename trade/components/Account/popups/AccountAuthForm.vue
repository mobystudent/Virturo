<template>
  <transition name="modal" appear>
    <div class="popup-wrapper">
      <div class="popup-container">
        <p class="title">Activate Two-Factor Authentication</p>
        <span class="subtitle">Help protect your account from unauthorized access by requiring a second authentication method</span>
        <div class="step">
          <div class="paragraph-number">1</div>
          <p>Download the Google Authenticator app</p>
        </div>
        <div class="step-action">
          <img class="google-play" src="~/static/img/google-play.png" />
          <img class="app-store" src="~/static/img/app-store.png" />
        </div>
        <div class="step">
          <div class="paragraph-number">2</div>
          <p>Scan the QR Code</p>
        </div>
        <div class="qr-code">
          <div v-html="resizeSvg(svg)"></div>
        </div>
        <div class="step">
          <div class="paragraph-number">3</div>
          <p>Enter the 6-digit code generated by the app</p>
        </div>
        <div class="step-action">
          <div class="inputs-group">
            <input
              v-for="(_digit, index) in digits"
              :key="index"
              ref="digits"
              v-model="digits[index]"
              type="number"
              class="single-input"
              :class="isError ? 'invalid' : ''"
              @input.prevent="e => handleDigitInput(e, index)"
              @focus="isError = false"
            />
          </div>
        </div>
        <span v-if="isError" class="error-label">Incorrect code</span>
        <CloseIcon class="close" @click="$emit('close')" />
      </div>
    </div>
  </transition>
</template>

<script>
import CloseIcon from '@/static/img/icons/close-popup.svg?inline';

export default {
  name: 'AccountAuthForm',
  components: { CloseIcon },
  data() {
    return {
      digits: Array(6).fill(''),
      isError: false,
      svg: '',
    };
  },
  mounted() {
    this.loadSvg();
  },
  methods: {
    async sendCode() {
      try {
        await this.$http.post('/api/auth/verify-auth-2fa', { code: this.digits.join('') });

        await this.$http.post('/api/auth/change-auth-2fa', { two_fa: true });
        this.$store.dispatch('user/setTwoFa', true);
        this.$emit('openSuccessPopup');
      } catch (e) {
        // console.log(e);
        this.isError = true;
      }
    },
    resizeSvg(svg) {
      const resizedSvg = svg.replace(/width="[^"]+"/, 'width="108px"');
      const finalSvg = resizedSvg.replace(/height="[^"]+"/, 'height="108px"');
      return finalSvg;
    },
    loadSvg() {
      this.$http
        .get('/api/auth/get-qr-code-2FA')
        .then(async res => {
          this.svg = await res.text();
        })
        .catch(e => {
          // console.log(e)
        });
    },
    handleDigitInput(e, index) {
      const value = e.target.value.replace(/[^0-9]/g, '');
      this.digits[index] = value.slice(0, 1);

      if (value.length > 1) {
        let i = 1;
        for (i; i < this.digits.length; i++) {
          if (typeof this.digits[index + i] !== 'undefined' && value[i]) {
            this.digits[index + i] = value[i];
          } else {
            break;
          }
        }
        if (index + i < this.digits.length) {
          this.$refs.digits[index + i].focus();
        } else if (this.digits.slice(0, index).includes('')) {
          const idx = this.digits.slice(0, index).findIndex(el => el === '');
          this.$refs.digits[idx].focus();
        }
      } else if (index + 1 !== this.digits.length && value !== '') {
        this.$refs.digits[index + 1].focus();
      }

      const isValid = this.digits.every(digit => !!digit);

      if (isValid) {
        this.sendCode();
      }
    },
  },
};
</script>

