    <h2>Anti-Money Laundering (AML) Policy</h2>

    <p>Virturo is dedicated to preventing and mitigating the risks of money laundering, terrorist financing, and other illicit activities. This AML Policy outlines the measures and practices implemented to ensure compliance with international AML standards, including but not limited to FATF recommendations, EU AML Directives, and applicable local laws.</p>

    <h3>Scope</h3>
    <p>This policy applies to all users of Virturo’s platform, employees, contractors, and partners. It governs all financial transactions and user activities conducted via the platform.</p>

    <h3>Key Measures</h3>
    <p>
      All users are required to complete identity verification under Virturo’s KYC policy before accessing the platform’s services. Politically Exposed Persons (PEPs) and users from high-risk jurisdictions are strictly prohibited from registering or using the platform. Transactions are monitored in real-time using advanced analytics and automated detection tools, with suspicious patterns flagged for review by the compliance team.<br>
      Transaction records, user activity logs, and identification documentation are retained for a minimum of five years to meet record-keeping obligations. Suspicious activity reports (SARs) are filed with the relevant regulatory authorities as required by law, and Virturo reserves the right to suspend or terminate accounts suspected of involvement in money laundering activities.<br>
      Cross-border transactions are subject to enhanced scrutiny and verification to address international money laundering risks. Virturo also conducts regular audits of its AML policies and procedures to maintain compliance with evolving regulations and internal standards.
    </p>

    <h3>Training and Awareness</h3>
    <p>Virturo provides ongoing AML training for employees to ensure they stay informed on best practices and regulatory updates. This approach reinforces the company’s commitment to maintaining a robust AML framework.</p>

    <h3>Audit and Review</h3>
    <p>Virturo periodically reviews its AML policies and practices to align with the latest legal, regulatory, and operational developments. This proactive approach ensures the effectiveness of the platform’s anti-money laundering measures.</p>
